# REF-StandbyHibernate-Build.ps1 - builds the StandbyHibernate remediation (12 Oct 2026). RA-027 F12.
# Writes REF-StandbyHibernate-Detect.ps1 and -Remediate.ps1 next to this file from ONE core (same pattern as
# REF-FW-VersionedPaths-Build.ps1), so the Intune detection, the Intune remediation and the local runner never disagree.
#
# WHY (sleep study 9-12 Oct, Evidence\2026-10-12\sleepstudy-WS01.html): WS01 enters Modern Standby (S0 low power idle)
# at every screen-off and stayed there up to 7 h 10 min on battery; the tenant 'hibernate after 300 s' policy is never
# applied to Modern Standby (the only hibernations were at Battery PreCritical). While it is open and locked, the BitLocker
# keys stay in memory. Lid / power / sleep button already = shut down.
# WHAT: a SYSTEM task (every 5 minutes with wake-to-run, plus at every session lock) runs the core. The core decides from
# LogonUI.exe being present (lock or sign-in screen) how long the console has been locked; at 15 minutes it hibernates the
# machine once per lock (Enforce) or only records that it would (Observe). It never acts twice for the same lock and
# changes no setting. Windows servicing is recorded on every run (SERVICING=) but is not a guard: TiWorker was found running
# idle on 12 Oct with no reboot pending, so a guard on it could prevent the hibernate indefinitely. Every run writes one event to the
# REF log (source REF-Standby, id 4100; 4101 = would/did hibernate), which Sentinel collects.
# TEST FIRST (Security Officer, 12 Oct): build with -Mode Observe, deploy, leave WS01 locked >30 min, then compare the
# 4100 events with Kernel-Power 506/507. Only if the task demonstrably runs during Modern Standby: rebuild -Mode Enforce
# and update the remediation content.
param([ValidateSet('Observe', 'Enforce')][string]$Mode = 'Observe', [int]$LockMinutes = 15)
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$runnerPath = 'C:\ProgramData\REF\REF-StandbyHibernate.ps1'
$task = 'REF-StandbyHibernate'

$core = @'
# REF-StandbyHibernate core v1 __MODE__ (12 Oct 2026). Generated by REF-StandbyHibernate-Build.ps1 - do not edit by hand.
# Hibernates the machine once it has been locked (or at the sign-in screen) for __MIN__ minutes, once per lock, so BitLocker
# keys do not stay in memory during Modern Standby. Mode Observe only records what it would do. Changes no setting.
$ErrorActionPreference = 'Continue'
$Mode = '__MODE__'; $LockMinutes = __MIN__
$statePath = 'C:\ProgramData\REF\REF-StandbyHibernate.state.json'
function Log($id, $msg) { try { Write-EventLog -LogName REF -Source 'REF-Standby' -EventId $id -EntryType Information -Message $msg } catch { } }
$now = Get-Date
$locked = [bool](Get-Process -Name LogonUI -ErrorAction SilentlyContinue)
$st = $null; try { if (Test-Path -LiteralPath $statePath) { $st = Get-Content -LiteralPath $statePath -Raw | ConvertFrom-Json } } catch { }
if (-not $st) { $st = [pscustomobject]@{ LockedSince = ''; Acted = $false } }
$power = try { $b = @(Get-CimInstance Win32_Battery -ErrorAction Stop)[0]; if ($b.BatteryStatus -eq 2) { 'AC' } else { "battery $($b.EstimatedChargeRemaining)%" } } catch { 'unknown' }
$mins = 0
if (-not $locked) { $st.LockedSince = ''; $st.Acted = $false; $decision = 'unlocked' }
else {
    if (-not $st.LockedSince) { $st.LockedSince = $now.ToString('o') }
    $mins = [math]::Round(($now - [datetime]$st.LockedSince).TotalMinutes, 1)
    if ($st.Acted) { $decision = 'already acted for this lock' }
    elseif ($mins -lt $LockMinutes) { $decision = "locked $mins min (< $LockMinutes)" }
    elseif ($Mode -eq 'Enforce') { $decision = 'HIBERNATE'; $st.Acted = $true }
    else { $decision = 'WOULD HIBERNATE (observe mode)'; $st.Acted = $true }
}
try { $st | ConvertTo-Json | Set-Content -LiteralPath $statePath -Encoding UTF8 } catch { }
# servicing is recorded, not used as a guard: TiWorker can sit idle for hours and Windows handles hibernate during servicing
$svc = if (Get-Process -Name TiWorker -ErrorAction SilentlyContinue) { 'yes' } else { 'no' }
$msg = "MODE=$Mode | LOCKED=$locked | LOCKED_SINCE=$($st.LockedSince) | LOCKED_MIN=$mins | POWER=$power | SERVICING=$svc | DECISION=$decision"
if ($decision -eq 'HIBERNATE' -or $decision -like 'WOULD*') { Log 4101 $msg } else { Log 4100 $msg }
if ($decision -eq 'HIBERNATE') { & "$env:SystemRoot\System32\shutdown.exe" /h }
'@ -replace '__MODE__', $Mode -replace '__MIN__', "$LockMinutes"

$common = @'
$ErrorActionPreference = 'Continue'
$runnerPath = '__RUNNER__'
$taskName = '__TASK__'
$taskArgs = '-NoProfile -NonInteractive -ExecutionPolicy Bypass -File "__RUNNER__"'
function Norm($s) { ($s -replace "`r`n", "`n").Trim() }
function Test-RunnerAcl($p) {
    # Runs as SYSTEM: only SYSTEM and Administrators may change it, or a standard user could get code run as SYSTEM.
    $bad = @((Get-Acl -LiteralPath $p).Access | Where-Object { $_.AccessControlType -eq 'Allow' -and "$($_.FileSystemRights)" -match 'Write|Modify|FullControl|ChangePermissions|TakeOwnership|Delete' -and "$($_.IdentityReference)" -notmatch '^(NT AUTHORITY\\SYSTEM|BUILTIN\\Administrators)$' })
    $bad.Count -eq 0
}
function Test-Task {
    $t = Get-ScheduledTask -TaskName $taskName -ErrorAction SilentlyContinue
    if (-not $t) { return 'missing' }
    if ("$($t.State)" -eq 'Disabled') { return 'disabled' }
    if ("$($t.Principal.UserId)" -notmatch 'SYSTEM') { return "runs as $($t.Principal.UserId)" }
    if ("$($t.Actions[0].Arguments)" -ne $taskArgs) { return 'action changed' }
    if (-not @($t.Triggers | Where-Object { "$($_.Repetition.Interval)" -eq 'PT5M' }).Count) { return 'no 5-minute trigger' }
    if (-not @($t.Triggers | Where-Object { $_.CimClass.CimClassName -eq 'MSFT_TaskSessionStateChangeTrigger' -and $_.StateChange -eq 7 }).Count) { return 'no session-lock trigger' }
    if (-not $t.Settings.WakeToRun) { return 'wake-to-run off' }
    return 'ok'
}
'@ -replace '__RUNNER__', $runnerPath -replace '__TASK__', $task

$elev = @'
if (-not ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    Write-Output 'REFUSING TO RUN: must be elevated (Intune runs this as SYSTEM).'; exit 2 }
'@

$detect = @"
# REF-StandbyHibernate - DETECTION v1 $Mode (12 Oct 2026). Generated by REF-StandbyHibernate-Build.ps1 - do not edit by hand.
# Exit 1 when the runner is missing, differs from the tenant copy or is writable by a non-administrator, or when its task
# (SYSTEM, every 5 minutes with wake-to-run, and at session lock) is missing or altered. RA-027 F12; NIST 3.13.16, 3.1.10.
$elev
$common
`$core = @'
$core
'@
`$need = @()
if (-not (Test-Path -LiteralPath `$runnerPath)) { `$need += 'NEED runner missing' }
elseif ((Norm (Get-Content -LiteralPath `$runnerPath -Raw)) -ne (Norm `$core)) { `$need += 'NEED runner content differs from the tenant copy' }
elseif (-not (Test-RunnerAcl `$runnerPath)) { `$need += 'NEED runner writable by a non-administrator' }
`$ts = Test-Task; if (`$ts -ne 'ok') { `$need += "NEED task: `$ts" }
if (`$need.Count) { Write-Output (`$need -join '; '); exit 1 }
Write-Output 'StandbyHibernate runner ($Mode) present, locked and scheduled'
exit 0
"@

$remediate = @"
# REF-StandbyHibernate - REMEDIATION v1 $Mode (12 Oct 2026). Generated by REF-StandbyHibernate-Build.ps1 - do not edit by hand.
# 1. Writes the core to $runnerPath and locks it (SYSTEM and Administrators only; Users read and execute).
# 2. Creates event source REF-Standby in the REF log.
# 3. Registers task ${task}: SYSTEM, every 5 minutes with wake-to-run, and at every session lock. Changes no other setting.
$elev
$common
`$core = @'
$core
'@
`$log = @()
New-Item -ItemType Directory -Force -Path (Split-Path `$runnerPath) | Out-Null
if (-not (Test-Path -LiteralPath `$runnerPath) -or (Norm (Get-Content -LiteralPath `$runnerPath -Raw)) -ne (Norm `$core)) { Set-Content -LiteralPath `$runnerPath -Value `$core -Encoding UTF8; `$log += 'runner written' }
if (-not (Test-RunnerAcl `$runnerPath)) {
    & "`$env:SystemRoot\System32\icacls.exe" `$runnerPath /inheritance:r /grant:r '*S-1-5-18:(F)' '*S-1-5-32-544:(F)' '*S-1-5-32-545:(RX)' | Out-Null
    `$log += "runner locked (icacls exit `$LASTEXITCODE)" }
try { if (-not [System.Diagnostics.EventLog]::SourceExists('REF-Standby')) { New-EventLog -LogName REF -Source 'REF-Standby' -ErrorAction Stop; `$log += 'event source created' } } catch { `$log += "event source: `$(`$_.Exception.Message)" }
`$ts = Test-Task
if (`$ts -ne 'ok') {
    `$a = New-ScheduledTaskAction -Execute "`$env:SystemRoot\System32\WindowsPowerShell\v1.0\powershell.exe" -Argument `$taskArgs
    `$t1 = New-ScheduledTaskTrigger -Once -At (Get-Date).AddMinutes(1) -RepetitionInterval (New-TimeSpan -Minutes 5)
    `$cls = Get-CimClass -Namespace 'Root/Microsoft/Windows/TaskScheduler' -ClassName 'MSFT_TaskSessionStateChangeTrigger'
    `$t2 = New-CimInstance -CimClass `$cls -ClientOnly; `$t2.StateChange = 7; `$t2.Enabled = `$true
    `$p = New-ScheduledTaskPrincipal -UserId 'SYSTEM' -LogonType ServiceAccount -RunLevel Highest
    `$s = New-ScheduledTaskSettingsSet -WakeToRun -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable -MultipleInstances IgnoreNew -ExecutionTimeLimit (New-TimeSpan -Minutes 2)
    Register-ScheduledTask -TaskName `$taskName -Description 'Sanctir: hibernates the machine after it has been locked for $LockMinutes minutes, once per lock, so disk-encryption keys do not stay in memory during Modern Standby (mode: $Mode). Read C:\ProgramData\REF\REF-StandbyHibernate.ps1 for exactly what it does.' -Action `$a -Trigger `$t1, `$t2 -Principal `$p -Settings `$s -Force | Out-Null
    `$log += "task registered (was: `$ts)" }
Write-Output (`$(if (`$log.Count) { `$log -join '; ' } else { 'nothing to change' }))
exit 0
"@

$enc = New-Object Text.UTF8Encoding($false)
[IO.File]::WriteAllText((Join-Path $here 'REF-StandbyHibernate-Detect.ps1'), $detect, $enc)
[IO.File]::WriteAllText((Join-Path $here 'REF-StandbyHibernate-Remediate.ps1'), $remediate, $enc)
foreach ($n in 'Detect', 'Remediate') { $p = Join-Path $here "REF-StandbyHibernate-$n.ps1"; $e = $null; [void][System.Management.Automation.Language.Parser]::ParseFile($p, [ref]$null, [ref]$e); "{0,-10} {1} {2} sha8 {3}" -f $n, $Mode, $(if ($e) { "PARSE ERROR: $($e[0].Message) line $($e[0].Extent.StartLineNumber)" } else { 'parse OK' }), (Get-FileHash $p -Algorithm SHA256).Hash.Substring(0, 8) }
