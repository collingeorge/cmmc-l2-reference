# REF-FWLocalLockdown-Build.ps1 - builds the "SANCTIR - Firewall Local Rule Lockdown" remediation (10 Oct 2026; v3 11 Oct).
# Writes REF-FWLocalLockdown-Detect.ps1, -Remediate.ps1 and -Core.ps1 next to this file from ONE core, which is also the
# locked local runner C:\ProgramData\REF\REF-FW-Lockdown.ps1 behind task REF-FW-Lockdown.
#
# WHY. 10 Oct 2026 the Security Officer reduced WS01's enabled local firewall allow rules from 340 to 127. Windows and app
# updates re-create and re-enable their own rules, so without enforcement the reduction drifts back. 11 Oct: "detect changes
# and immediately remediate" - the hourly Intune run is not immediate, so v3 adds a local task that fires on the firewall
# rule-change audit events the moment a rule is added, changed or re-enabled. NIST 3.4.7, 3.13.6, 3.13.1.
# WHAT.
#   Rules: any ENABLED local (PersistentStore) ALLOW rule that is not group REF-Remediated, display group Core Networking,
#   a management / security / tunnel program, or an OUTBOUND rule on the Security Officer's reviewed keep list is DISABLED
#   (never deleted) and listed in SANCTIR event 1110 (collected into Sentinel).
#   Profiles: every profile enabled, default Block in and out, blocked connections logged. MDM owns these (ActiveStore wins);
#   if the active values ever differ, the local store is re-asserted and event 1112 is written.
#   Triggers: Security 4946 (rule added), 4947 (rule modified), 4948 (rule deleted), 4950 (profile setting changed),
#   4954 (policy changed) - needs audit subcategory "MPSSVC Rule-Level Policy Change"; plus startup and every 15 minutes;
#   plus the hourly Intune run (which also verifies the runner, its lock and the task, and re-installs them).
# SAFETY. Connectivity is tested (Entra, Intune, Defender updates, Windows Update, Azure Monitor) before and after; if it was
# fine before and fails after, every rule disabled in that run is re-enabled at once and event 1111 (error) is written.
# Local policy merge stays ON (GAP-022 §5): turning it off would also drop the tenant's own versioned-path rules.
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path

$core = @'
# SANCTIR Firewall Local Rule Lockdown core v3 (11 Oct 2026; v3 event-triggered runner, profile defaults; v2 Store package names as SYSTEM).
# Generated by REF-FWLocalLockdown-Build.ps1 - do not edit by hand.
# REF-BUILD: __STAMP__
param([string]$Mode = 'Check')
$critical = 'warp-svc|Cloudflare|MsMpEng|MsSense|SenseNdr|SenseCncProxy|MpDefenderCoreService|NisSrv|Microsoft\.Management\.Services\.IntuneWindowsAgent|AgentExecutor|IntuneManagementExtension|himds|gc_service|gc_arc_service|MonAgent|AzureConnectedMachineAgent|ExtensionService'
$keepOutbound = '^(Windows Device Management|Work or school account|Cloud Identity|Email and accounts|Captive Portal Flow|Windows Defender SmartScreen|Windows Security|DiagTrack|Company Portal|Microsoft Store|App Installer|Store Experience Host|Windows Print|Print Queue|Brother Print Support App|Microsoft 365 Copilot|Microsoft Teams|Claude|ChatGPT|OfficePushNotificationsUtility|Microsoft\.Office\.ActionsServer|Microsoft Sticky Notes)$'
$keepOutboundNames = 'Claude|ChatGPT|codex|Microsoft 365 Copilot|M365Copilot|Microsoft Teams|ms-teams'
# As SYSTEM, Store packages' ms-resource display names do not resolve; package names are matched too (v2).
$keepOutboundPkgs = 'Microsoft\.CompanyPortal_|Microsoft\.SecHealthUI_|Microsoft\.DesktopAppInstaller_|Microsoft\.StorePurchaseApp_|Microsoft\.WindowsStore_|Microsoft\.MicrosoftStickyNotes_|MSTeams_|Microsoft\.MicrosoftOfficeHub_|OpenAI\.|Claude_|Brother|Microsoft\.AAD\.BrokerPlugin_|Microsoft\.AccountsControl_|Microsoft\.Windows\.CloudExperienceHost_'
function Ev($id, $type, $msg) { try { Write-EventLog -LogName REF -Source 'REF-Watchdog' -EventId $id -EntryType $type -Message $msg -ErrorAction Stop } catch { } }
function Test-Net {
    $bad = @()
    foreach ($h in 'login.microsoftonline.com', 'manage.microsoft.com', 'definitionupdates.microsoft.com', 'update.microsoft.com', 'global.handler.control.monitor.azure.com') {
        $ok = $false
        foreach ($i in 1..3) {
            try { $ip = @(Resolve-DnsName $h -QuickTimeout -ErrorAction Stop | Where-Object { $_.IPAddress -and $_.IPAddress -notin '0.0.0.0', '::' } | Sort-Object { $_.IPAddress -match ':' })[0].IPAddress
                  $c = New-Object Net.Sockets.TcpClient; try { if ($c.ConnectAsync($ip, 443).Wait(5000) -and $c.Connected) { $ok = $true } } finally { $c.Dispose() } } catch { }
            if ($ok) { break }; Start-Sleep -Seconds 2
        }
        if (-not $ok) { $bad += $h }
    }
    , $bad
}
$out = @()
# --- profiles (MDM-owned; verified, re-asserted locally if the active values differ) ---
$badProf = @(Get-NetFirewallProfile -PolicyStore ActiveStore | Where-Object { $_.Enabled -ne 'True' -or "$($_.DefaultInboundAction)" -ne 'Block' -or "$($_.DefaultOutboundAction)" -ne 'Block' -or $_.LogBlocked -ne 'True' })
if ($badProf.Count) {
    $d = ($badProf | ForEach-Object { "$($_.Name): on=$($_.Enabled) in=$($_.DefaultInboundAction) out=$($_.DefaultOutboundAction) logBlocked=$($_.LogBlocked)" }) -join '; '
    if ($Mode -eq 'Fix') { foreach ($p in $badProf) { Set-NetFirewallProfile -PolicyStore PersistentStore -Name $p.Name -Enabled True -DefaultInboundAction Block -DefaultOutboundAction Block -LogBlocked True -ErrorAction SilentlyContinue }; Ev 1112 'Error' "Firewall profile defaults were not Block/Block/logged ($d). Local store re-asserted; the MDM policy should own these - investigate."; $out += "profile defaults re-asserted ($d)" }
    else { $out += "NEED profile defaults: $d" }
}
# --- rules ---
$rules = @(Get-NetFirewallRule -PolicyStore PersistentStore -ErrorAction Stop | Where-Object { $_.Enabled -eq 'True' -and $_.Action -eq 'Allow' })
$app = @{}; Get-NetFirewallApplicationFilter -PolicyStore PersistentStore | ForEach-Object { $app[$_.InstanceID] = $_ }
$svc = @{}; Get-NetFirewallServiceFilter -PolicyStore PersistentStore | ForEach-Object { $svc[$_.InstanceID] = $_ }
$cand = @(foreach ($r in $rules) {
    $prog = "$($app[$r.Name].Program)"; $srv = "$($svc[$r.Name].Service)"
    if ($r.Group -eq 'REF-Remediated' -or "$($r.DisplayGroup)" -eq 'Core Networking') { continue }
    if ("$prog $srv $($r.DisplayName)" -match $critical) { continue }
    if ("$($r.Direction)" -eq 'Outbound' -and ("$($r.DisplayGroup)" -match $keepOutbound -or "$($r.DisplayName)" -match $keepOutbound -or "$($r.DisplayName) $prog" -match $keepOutboundNames -or "$($r.DisplayName) $($r.DisplayGroup) $prog" -match $keepOutboundPkgs)) { continue }
    $r })
$label = { param($x) "$($x.Direction) $($x.DisplayName)$(if ($x.DisplayGroup -and $x.DisplayGroup -notmatch '^\{') { " [$($x.DisplayGroup)]" })" }
if ($Mode -ne 'Fix') {
    if ($cand.Count) { $out += "NEED $($cand.Count) local allow rule(s) not set by the organisation: " + ((@($cand | Select-Object -First 15) | ForEach-Object { & $label $_ }) -join '; ') }
    elseif (-not $out.Count) { $out += "OK $($rules.Count) enabled local allow rules, all the organisation's (Core Networking, REF-Remediated, management/security, reviewed outbound); profiles Block/Block/logged" }
    $out; return
}
if (-not $cand.Count) { $out += "rules: nothing to change ($($rules.Count) enabled local allow rules, all the organisation's)"; $out; return }
$before = Test-Net
$cand | ForEach-Object { Disable-NetFirewallRule -PolicyStore PersistentStore -Name $_.Name -ErrorAction SilentlyContinue }
$names = (@($cand | Select-Object -First 40) | ForEach-Object { & $label $_ }) -join "`r`n"
if (-not $before.Count) {
    Start-Sleep -Seconds 5; $after = Test-Net
    if ($after.Count) {
        $cand | ForEach-Object { Enable-NetFirewallRule -PolicyStore PersistentStore -Name $_.Name -ErrorAction SilentlyContinue }
        Ev 1111 'Error' ("Firewall lockdown ROLLED BACK: connectivity failed after disabling $($cand.Count) rule(s) ($($after -join ', ')). Rules:`r`n$names")
        $out += "FAILED: connectivity lost after disabling $($cand.Count) rule(s) ($($after -join ', ')); all re-enabled"; $out; return
    }
}
Ev 1110 'Warning' ("Firewall lockdown: $($cand.Count) local allow rule(s) not set by the organisation were disabled (re-created or re-enabled by Windows or an app):`r`n$names")
$out += "disabled $($cand.Count) local allow rule(s) not set by the organisation$(if ($before.Count) { " (connectivity was already failing before the change: $($before -join ', '); not rolled back)" })"
$out
'@
$core = $core -replace '__STAMP__', (Get-Date -Format 'yyyyMMddHHmm')

$runnerPath = 'C:\ProgramData\REF\REF-FW-Lockdown.ps1'
$task = 'REF-FW-Lockdown'
$common = @'
$ErrorActionPreference = 'Continue'
$runnerPath = '__RUNNER__'; $taskName = '__TASK__'
$taskArgs = '-NoProfile -NonInteractive -ExecutionPolicy Bypass -File "__RUNNER__" -Mode Fix'
# Fires the moment a firewall rule is added (4946), changed (4947), deleted (4948), a profile setting changes (4950) or the
# policy changes (4954). Needs audit subcategory "MPSSVC Rule-Level Policy Change" (in the tenant audit policy).
$subscription = '<QueryList><Query Id="0" Path="Security"><Select Path="Security">*[System[(EventID=4946 or EventID=4947 or EventID=4948 or EventID=4950 or EventID=4954)]]</Select></Query></QueryList>'
function Norm($s) { ($s -replace "`r`n", "`n").Trim() }
function Stamp($s) { if ("$s" -match 'REF-BUILD:\s*(\d{12})') { [long]$Matches[1] } else { [long]0 } }
function Test-RunnerAcl($p) {
    $bad = @((Get-Acl -LiteralPath $p).Access | Where-Object { $_.AccessControlType -eq 'Allow' -and "$($_.FileSystemRights)" -match 'Write|Modify|FullControl|ChangePermissions|TakeOwnership|Delete' -and "$($_.IdentityReference)" -notmatch '^(NT AUTHORITY\\SYSTEM|BUILTIN\\Administrators)$' })
    $bad.Count -eq 0
}
function Test-Task {
    $t = Get-ScheduledTask -TaskName $taskName -ErrorAction SilentlyContinue
    if (-not $t) { return 'missing' }
    if ("$($t.State)" -eq 'Disabled') { return 'disabled' }
    if ("$($t.Principal.UserId)" -notmatch 'SYSTEM') { return "runs as $($t.Principal.UserId)" }
    if ("$($t.Actions[0].Arguments)" -ne $taskArgs) { return 'action changed' }
    if (-not @($t.Triggers | Where-Object { "$($_.Repetition.Interval)" -eq 'PT15M' }).Count) { return 'no 15-minute trigger' }
    if (-not @($t.Triggers | Where-Object { $_.CimClass.CimClassName -eq 'MSFT_TaskBootTrigger' }).Count) { return 'no startup trigger' }
    $ev = @($t.Triggers | Where-Object { $_.CimClass.CimClassName -eq 'MSFT_TaskEventTrigger' })
    if (-not $ev.Count) { return 'no rule-change trigger' }
    if ("$($ev[0].Subscription)" -ne $subscription) { return 'rule-change trigger outdated' }
    return 'ok'
}
'@ -replace '__RUNNER__', $runnerPath -replace '__TASK__', $task
$elev = @'
if (-not ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    Write-Output 'REFUSING TO RUN: must be elevated (Intune runs this as SYSTEM).'; exit 2 }
'@
$detect = @"
# REF-FWLocalLockdown-Detect v3 (11 Oct 2026). Generated by REF-FWLocalLockdown-Build.ps1 - do not edit by hand.
# Exit 1 when an enabled local firewall ALLOW rule is not the organisation's, a profile default is wrong, or the local
# runner (file, lock, task, triggers) is missing or altered. NIST 3.4.7, 3.13.6. Runs as SYSTEM.
$elev
$common
`$core = @'
$core
'@
`$need = @()
try { `$r = @(& ([scriptblock]::Create(`$core)) -Mode Check); if (`$r -match '^NEED') { `$need += `$r } } catch { `$need += "check could not run: `$(`$_.Exception.Message)" }
if (-not (Test-Path -LiteralPath `$runnerPath)) { `$need += 'runner file missing' }
elseif ((Norm (Get-Content -LiteralPath `$runnerPath -Raw)) -ne (Norm `$core) -and (Stamp (Get-Content -LiteralPath `$runnerPath -Raw)) -le (Stamp `$core)) { `$need += 'runner file differs from the tenant copy' }
elseif (-not (Test-RunnerAcl `$runnerPath)) { `$need += 'runner file writable by a non-administrator' }
`$ts = Test-Task; if (`$ts -ne 'ok') { `$need += "runner task: `$ts" }
if (`$need.Count) { Write-Output (`$need -join '; '); exit 1 }
Write-Output "Firewall lockdown met: `$(`$r -join '; '); runner present, locked and scheduled (startup, 15 min, rule-change events)"
exit 0
"@
$remediate = @"
# REF-FWLocalLockdown-Remediate v3 (11 Oct 2026). Generated by REF-FWLocalLockdown-Build.ps1 - do not edit by hand.
# 1. Writes the core to $runnerPath and locks it (SYSTEM and Administrators only); never downgrades a newer installed copy.
# 2. Registers task ${task}: SYSTEM, at startup, every 15 minutes, and on firewall rule-change audit events.
# 3. Runs the core once (disables non-organisation local allow rules; rolls back if connectivity fails).
$elev
$common
`$core = @'
$core
'@
`$log = @()
New-Item -ItemType Directory -Force -Path (Split-Path `$runnerPath) | Out-Null
if (-not (Test-Path -LiteralPath `$runnerPath)) { Set-Content -LiteralPath `$runnerPath -Value `$core -Encoding UTF8; `$log += 'runner written' }
elseif ((Norm (Get-Content -LiteralPath `$runnerPath -Raw)) -ne (Norm `$core)) {
    if ((Stamp (Get-Content -LiteralPath `$runnerPath -Raw)) -gt (Stamp `$core)) { `$log += 'installed runner is newer than this copy - kept (no downgrade)' }
    else { Set-Content -LiteralPath `$runnerPath -Value `$core -Encoding UTF8; `$log += 'runner written' } }
if (-not (Test-RunnerAcl `$runnerPath)) { & "`$env:SystemRoot\System32\icacls.exe" `$runnerPath /inheritance:r /grant:r '*S-1-5-18:(F)' '*S-1-5-32-544:(F)' '*S-1-5-32-545:(RX)' | Out-Null; `$log += "runner locked (icacls exit `$LASTEXITCODE)" }
try { if (-not [System.Diagnostics.EventLog]::SourceExists('REF-Watchdog')) { New-EventLog -LogName REF -Source 'REF-Watchdog' -ErrorAction Stop; `$log += 'event source created' } } catch { `$log += "event source: `$(`$_.Exception.Message)" }
`$ts = Test-Task
if (`$ts -ne 'ok') {
    `$a  = New-ScheduledTaskAction -Execute "`$env:SystemRoot\System32\WindowsPowerShell\v1.0\powershell.exe" -Argument `$taskArgs
    `$t1 = New-ScheduledTaskTrigger -AtStartup
    `$t2 = New-ScheduledTaskTrigger -Once -At (Get-Date).AddMinutes(2) -RepetitionInterval (New-TimeSpan -Minutes 15)
    `$cls = Get-CimClass -Namespace 'Root/Microsoft/Windows/TaskScheduler' -ClassName MSFT_TaskEventTrigger
    `$t3 = New-CimInstance -CimClass `$cls -ClientOnly; `$t3.Enabled = `$true; `$t3.Subscription = `$subscription
    `$p  = New-ScheduledTaskPrincipal -UserId 'SYSTEM' -LogonType ServiceAccount -RunLevel Highest
    `$s  = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable -MultipleInstances IgnoreNew -ExecutionTimeLimit (New-TimeSpan -Minutes 3)
    Register-ScheduledTask -TaskName `$taskName -Description 'Sanctir: keeps local firewall allow rules to the organisation''s list; fires on firewall rule-change audit events, at startup and every 15 minutes. Read C:\ProgramData\REF\REF-FW-Lockdown.ps1 for exactly what it does.' -Action `$a -Trigger `$t1, `$t2, `$t3 -Principal `$p -Settings `$s -Force | Out-Null
    `$log += "runner task registered (was: `$ts)" }
`$r = @(& ([scriptblock]::Create(`$core)) -Mode Fix); `$log += `$r
Write-Output (`$log -join '; ')
if (`$r -match '^FAILED') { exit 1 }
exit 0
"@
