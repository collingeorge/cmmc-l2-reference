# REF-DNSGuard-Build.ps1 - builds v1 of the DNS Guard remediation (18 Oct 2026). Writes REF-DNSGuard-Detect.ps1 and
# -Remediate.ps1 next to this file from ONE core, so detection and remediation can never disagree.
#
# WHY. Network captures, 18 Oct 2026 (Evidence\2026-10-18\network-capture-WS01-*): in steady state every packet goes through
# the Cloudflare One tunnel, but for about one second each time the client reconnects (re-authentication, key rotation) the
# Windows DNS client falls back to the router (<router-ip>:53) - OneDrive, Teams, Windows notification and Claude API names
# went to the router/ISP, and connections opened in that second went direct. Cloudflare's own no-auth-no-internet lockdown was
# tested the same day and does NOT cover a reconnect (only an unregistered client). Security Officer, 18 Oct 2026: "add a kill
# switch ... the computer cannot connect without the tunnel"; "Yes build it, pilot on WS02".
# WHAT. A SYSTEM runner (every minute and at start-up) keeps two LOCAL outbound BLOCK rules (group REF-DNSGuard) on the
# Windows DNS Client service (svchost, service dnscache): UDP 53 and TCP 53/853 to every address EXCEPT loopback - the Cloudflare
# One resolver is 127.0.2.2/127.0.2.3, so normal lookups are untouched, and the client's own process (warp-svc) is not affected.
#   Tunnel up, or down for less than 3 minutes -> rules ON (a reconnect gap cannot leak DNS; lookups fail and retry).
#   Tunnel down 3 minutes or more             -> rules OFF, event 4201 (fail-safe: "never take a machine offline", management
#                                                and updates keep working, hotel login pages work after 3 minutes).
#   Tunnel back                               -> rules ON again, event 4202.
# Block rules are not touched by REF-FWLocalLockdown (it handles enabled local ALLOW rules only).
# PILOT: the remediation acts only on the hosts in $PilotHosts; on any other machine detection reports "not in pilot" and the
# remediation does nothing. To roll out: add the host here, rebuild, push with REF-Update-Remediation.ps1.
# WAY BACK: remove the host from $PilotHosts (the remediation then removes rules, task and runner), or locally as an
# administrator: Disable-NetFirewallRule -Group REF-DNSGuard.
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
# 18 Oct 2026: pilot on WS02 passed all four tests (reconnect capture 09:42 - no app DNS on the wire, pfirewall drops of
# Dnscache to <router-ip>:53 at 09:40; normal DNS; restart; 4-minute cable pull - 4201 at 09:48:48, 4202 at 09:50:50).
# Security Officer: roll out when proven -> WS01 added.
$PilotHosts = @('WS02', 'WS01')
$stamp = Get-Date -Format 'yyyy-MM-dd HH:mm'

$core = @'
# REF DNS Guard core v1 (18 Oct 2026). Generated by REF-DNSGuard-Build.ps1 - do not edit by hand. Runs as SYSTEM, every minute.
# Keeps DNS from leaving outside the Cloudflare One tunnel during reconnects; releases after 3 minutes of real tunnel outage.
$ErrorActionPreference = 'Continue'
$FailOpenMinutes = 3
$group = 'REF-DNSGuard'; $statePath = 'C:\ProgramData\REF\REF-DNSGuard.state.json'
function Log($id, $type, $msg) { try { Write-EventLog -LogName REF -Source 'REF-DNSGuard' -EventId $id -EntryType $type -Message $msg } catch { } }
# every address except IPv4 loopback 127/8, IPv6 ::/::1 and IPv4-mapped loopback ::ffff:127.0.0.0/104
$ranges = @('0.0.0.0-126.255.255.255', '128.0.0.0-255.255.255.255', '::2-::ffff:7eff:ffff', '::ffff:8000:0-ffff:ffff:ffff:ffff:ffff:ffff:ffff:ffff')
$want = @(
    @{ Name = 'REF-DNSGuard-UDP'; Proto = 'UDP'; Ports = @('53') },
    @{ Name = 'REF-DNSGuard-TCP'; Proto = 'TCP'; Ports = @('53', '853') }
)
foreach ($w in $want) {
    if (-not (Get-NetFirewallRule -Name $w.Name -PolicyStore PersistentStore -ErrorAction SilentlyContinue)) {
        New-NetFirewallRule -Name $w.Name -DisplayName "REF DNS Guard: block DNS outside the Cloudflare One resolver ($($w.Proto) $($w.Ports -join ','))" -Description 'Sanctir: the Windows DNS client may only use the Cloudflare One resolver (127.0.2.2/.3). Managed by C:\ProgramData\REF\REF-DNSGuard.ps1; released automatically after 3 minutes without the tunnel.' -Group $group -Direction Outbound -Action Block -Protocol $w.Proto -RemotePort $w.Ports -RemoteAddress $ranges -Program '%SystemRoot%\System32\svchost.exe' -Service 'dnscache' -Profile Any -Enabled True -PolicyStore PersistentStore | Out-Null
        Log 4200 Information "DNS Guard rule created: $($w.Name)"
    }
}
# tunnel state: the Cloudflare One virtual adapter is Up and holds its tunnel address
$a = Get-NetAdapter -ErrorAction SilentlyContinue | Where-Object { $_.InterfaceDescription -match 'Cloudflare WARP' }
$up = [bool]($a -and $a.Status -eq 'Up' -and (Get-NetIPAddress -InterfaceIndex $a.ifIndex -AddressFamily IPv4 -ErrorAction SilentlyContinue | Where-Object { $_.IPAddress -like '100.*' }))
$now = Get-Date
$st = $null; try { if (Test-Path -LiteralPath $statePath) { $st = Get-Content -LiteralPath $statePath -Raw | ConvertFrom-Json } } catch { }
if (-not $st) { $st = [pscustomobject]@{ LastUp = $now.ToString('o'); Released = $false } }
$rulesOn = @(Get-NetFirewallRule -Group $group -PolicyStore PersistentStore -ErrorAction SilentlyContinue | Where-Object Enabled -eq 'True').Count
if ($up) {
    $st.LastUp = $now.ToString('o')
    if ($rulesOn -lt $want.Count) { Enable-NetFirewallRule -Group $group -PolicyStore PersistentStore -ErrorAction SilentlyContinue }
    if ($st.Released) { $st.Released = $false; Log 4202 Information 'Cloudflare One tunnel is back: DNS Guard re-armed (DNS outside the tunnel blocked again).' }
} else {
    $down = [math]::Round(($now - [datetime]$st.LastUp).TotalMinutes, 1)
    if ($down -ge $FailOpenMinutes) {
        if ($rulesOn) { Disable-NetFirewallRule -Group $group -PolicyStore PersistentStore -ErrorAction SilentlyContinue }
        if (-not $st.Released) { $st.Released = $true; Log 4201 Warning "Cloudflare One tunnel down for $down minutes: DNS Guard RELEASED so the machine stays manageable (fail-safe). It re-arms when the tunnel returns." }
    } elseif ($rulesOn -lt $want.Count) { Enable-NetFirewallRule -Group $group -PolicyStore PersistentStore -ErrorAction SilentlyContinue }
}
try { $st | ConvertTo-Json | Set-Content -LiteralPath $statePath -Encoding UTF8 } catch { }
'@

$common = @"
`$PilotHosts = @($(($PilotHosts | ForEach-Object { "'$_'" }) -join ', '))
`$runnerPath = 'C:\ProgramData\REF\REF-DNSGuard.ps1'
`$taskName = 'REF-DNSGuard'
`$taskArgs = '-NoProfile -NonInteractive -ExecutionPolicy Bypass -File "C:\ProgramData\REF\REF-DNSGuard.ps1"'
function Norm(`$s) { (`$s -replace "``r``n", "``n").Trim() }
function Test-RunnerAcl(`$p) { `$bad = @((Get-Acl -LiteralPath `$p).Access | Where-Object { `$_.AccessControlType -eq 'Allow' -and "`$(`$_.FileSystemRights)" -match 'Write|Modify|FullControl|ChangePermissions|TakeOwnership|Delete' -and "`$(`$_.IdentityReference)" -notmatch '^(NT AUTHORITY\\SYSTEM|BUILTIN\\Administrators)$' }); `$bad.Count -eq 0 }
function Test-Task { `$t = Get-ScheduledTask -TaskName `$taskName -ErrorAction SilentlyContinue; if (-not `$t) { return 'missing' }; if ("`$(`$t.State)" -eq 'Disabled') { return 'disabled' }; if ("`$(`$t.Principal.UserId)" -notmatch 'SYSTEM') { return 'not SYSTEM' }; if ("`$(`$t.Actions[0].Arguments)" -ne `$taskArgs) { return 'action changed' }; if (-not @(`$t.Triggers | Where-Object { "`$(`$_.Repetition.Interval)" -eq 'PT1M' }).Count) { return 'no 1-minute trigger' }; if (-not @(`$t.Triggers | Where-Object { `$_.CimClass.CimClassName -eq 'MSFT_TaskBootTrigger' }).Count) { return 'no start-up trigger' }; 'ok' }
`$core = @'
$core
'@
"@

$detect = @"
# REF-DNSGuard - DETECTION (SYSTEM) v1, built $stamp by REF-DNSGuard-Build.ps1 - do not edit by hand. See the build script for the why.
`$ErrorActionPreference = 'SilentlyContinue'
$common
`$pilot = `$PilotHosts -contains `$env:COMPUTERNAME
if (-not `$pilot) {
    if ((Test-Path -LiteralPath `$runnerPath) -or (Get-ScheduledTask -TaskName `$taskName -ErrorAction SilentlyContinue) -or (Get-NetFirewallRule -Group 'REF-DNSGuard' -PolicyStore PersistentStore -ErrorAction SilentlyContinue)) { Write-Output 'Not in the DNS Guard pilot but pieces are present - remove'; exit 1 }
    Write-Output 'Not in the DNS Guard pilot - nothing installed'; exit 0 }
`$need = @()
if (-not (Test-Path -LiteralPath `$runnerPath) -or (Norm (Get-Content -LiteralPath `$runnerPath -Raw)) -ne (Norm `$core)) { `$need += 'runner missing or changed' }
elseif (-not (Test-RunnerAcl `$runnerPath)) { `$need += 'runner writable by non-admins' }
`$ts = Test-Task; if (`$ts -ne 'ok') { `$need += "task: `$ts" }
`$rules = @(Get-NetFirewallRule -Group 'REF-DNSGuard' -PolicyStore PersistentStore -ErrorAction SilentlyContinue)
if (`$rules.Count -lt 2) { `$need += "rules present: `$(`$rules.Count) of 2" }
`$state = try { Get-Content 'C:\ProgramData\REF\REF-DNSGuard.state.json' -Raw | ConvertFrom-Json } catch { `$null }
if (`$need.Count) { Write-Output ('DNS Guard NEEDS: ' + (`$need -join '; ')); exit 1 }
Write-Output "DNS Guard OK: rules `$(@(`$rules | Where-Object Enabled -eq 'True').Count)/2 on; released=`$(`$state.Released); tunnel last up `$(`$state.LastUp)"
exit 0
"@

$remediate = @"
# REF-DNSGuard - REMEDIATION (SYSTEM) v1, built $stamp by REF-DNSGuard-Build.ps1 - do not edit by hand. See the build script for the why.
if (-not ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) { Write-Output 'REFUSING: must run elevated (Intune runs this as SYSTEM).'; exit 2 }
`$ErrorActionPreference = 'Continue'
$common
`$log = @()
if (`$PilotHosts -notcontains `$env:COMPUTERNAME) {
    Unregister-ScheduledTask -TaskName `$taskName -Confirm:`$false -ErrorAction SilentlyContinue
    Get-NetFirewallRule -Group 'REF-DNSGuard' -PolicyStore PersistentStore -ErrorAction SilentlyContinue | Remove-NetFirewallRule -ErrorAction SilentlyContinue
    Remove-Item -LiteralPath `$runnerPath, 'C:\ProgramData\REF\REF-DNSGuard.state.json' -ErrorAction SilentlyContinue
    Write-Output 'Not in the DNS Guard pilot - task, rules and runner removed'; exit 0 }
New-Item -ItemType Directory -Force -Path (Split-Path `$runnerPath) | Out-Null
if (-not (Test-Path -LiteralPath `$runnerPath) -or (Norm (Get-Content -LiteralPath `$runnerPath -Raw)) -ne (Norm `$core)) { Set-Content -LiteralPath `$runnerPath -Value `$core -Encoding UTF8; `$log += 'runner written' }
if (-not (Test-RunnerAcl `$runnerPath)) { & "`$env:SystemRoot\System32\icacls.exe" `$runnerPath /inheritance:r /grant:r '*S-1-5-18:(F)' '*S-1-5-32-544:(F)' '*S-1-5-32-545:(RX)' | Out-Null; `$log += "runner locked (icacls `$LASTEXITCODE)" }
try { if (-not [System.Diagnostics.EventLog]::SourceExists('REF-DNSGuard')) { New-EventLog -LogName REF -Source 'REF-DNSGuard' -ErrorAction Stop; `$log += 'event source created' } } catch { `$log += "event source: `$(`$_.Exception.Message)" }
`$ts = Test-Task
if (`$ts -ne 'ok') {
    `$a = New-ScheduledTaskAction -Execute "`$env:SystemRoot\System32\WindowsPowerShell\v1.0\powershell.exe" -Argument `$taskArgs
    `$t1 = New-ScheduledTaskTrigger -Once -At (Get-Date).AddMinutes(1) -RepetitionInterval (New-TimeSpan -Minutes 1)
    `$t2 = New-ScheduledTaskTrigger -AtStartup
    `$p = New-ScheduledTaskPrincipal -UserId 'SYSTEM' -LogonType ServiceAccount -RunLevel Highest
    `$s = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable -MultipleInstances IgnoreNew -ExecutionTimeLimit (New-TimeSpan -Minutes 1)
    Register-ScheduledTask -TaskName `$taskName -Description 'Sanctir DNS Guard: blocks DNS that would leave outside the Cloudflare One tunnel during reconnects; releases automatically after 3 minutes without the tunnel. Read C:\ProgramData\REF\REF-DNSGuard.ps1.' -Action `$a -Trigger `$t1, `$t2 -Principal `$p -Settings `$s -Force | Out-Null
    `$log += "task registered (was: `$ts)" }
& "`$env:SystemRoot\System32\WindowsPowerShell\v1.0\powershell.exe" -NoProfile -NonInteractive -ExecutionPolicy Bypass -File `$runnerPath
`$rules = @(Get-NetFirewallRule -Group 'REF-DNSGuard' -PolicyStore PersistentStore -ErrorAction SilentlyContinue)
`$log += "rules `$(@(`$rules | Where-Object Enabled -eq 'True').Count)/`$(`$rules.Count) on"
Write-Output ('DNS Guard: ' + (`$log -join '; '))
if (`$rules.Count -lt 2) { exit 1 }
exit 0
"@

Set-Content -Path (Join-Path $here 'REF-DNSGuard-Detect.ps1') -Value $detect -Encoding UTF8
Set-Content -Path (Join-Path $here 'REF-DNSGuard-Remediate.ps1') -Value $remediate -Encoding UTF8
foreach ($f in 'REF-DNSGuard-Detect.ps1', 'REF-DNSGuard-Remediate.ps1') { $p = Join-Path $here $f; $t = $null; $e = $null; [System.Management.Automation.Language.Parser]::ParseFile($p, [ref]$t, [ref]$e) | Out-Null; "{0}: parse {1}, sha {2}" -f $f, $(if ($e) { "ERROR $($e[0].Extent.StartLineNumber): $($e[0].Message)" } else { 'OK' }), (Get-FileHash $p -Algorithm SHA256).Hash.Substring(0, 8) }
