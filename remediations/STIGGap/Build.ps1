# Builds REF-STIGGap-Detect.ps1 and REF-STIGGap-Remediate.ps1 from REF-STIGGap-Common.ps1 (+ -Certs.ps1).
# Intune runs each as a single file, so the shared body is copied into both. Edit Common, then rebuild.
#
# v2 (11 Oct 2026) - POLICY GUARD. The Security Officer: "detect changes and immediately remediate". The hourly Intune run
# re-applies the STIG settings within the hour; v2 also installs the same body as a locked local runner
# (C:\ProgramData\REF\REF-STIG-Guard.ps1) behind task REF-Policy-Guard, which fires on Security event 4657
# (registry value modified) by anyone other than SYSTEM, re-applies the settings at once, restarts the service watchdog
# check, and kicks an MDM sync so tenant policy is re-delivered. 4657 needs audit subcategory "Registry" (Object Access)
# and a SACL on the keys; the remediation sets a Success audit SACL (Everyone: set value, create/delete key, change
# permissions, take ownership) on HKLM\SOFTWARE\Policies and HKLM\SOFTWARE\Microsoft\PolicyManager\current. MDM writes are
# SYSTEM and are filtered out of the trigger, so normal syncs do not fire it.
$here = $PSScriptRoot; $common = Get-Content (Join-Path $here 'REF-STIGGap-Common.ps1') -Raw
$certs = Join-Path $here 'REF-STIGGap-Certs.ps1'; if (Test-Path $certs) { $common = (Get-Content $certs -Raw) + "`n" + $common }
$stamp = Get-Date -Format 'yyyyMMddHHmm'
$runnerBody = "# SANCTIR STIG policy guard runner (11 Oct 2026). Generated by REF-STIGGap-Build.ps1 - do not edit by hand.`n# REF-BUILD: $stamp`n" + $common + @'

# ---- GUARD RUN (event-triggered or at startup): re-apply, re-check the services, re-sync ----
$fixed = @(); try { Invoke-StigGap -Write; $fixed = @($script:Gaps) } catch { }
try { if ($fixed.Count) { Write-EventLog -LogName REF -Source 'REF-Watchdog' -EventId 1120 -EntryType Warning -Message ("Policy guard: a policy registry value was changed by a non-SYSTEM account; STIG settings re-applied: $($fixed.Count)`r`n" + ($fixed -join "`r`n")) -ErrorAction Stop } } catch { }
try { & "$env:SystemRoot\System32\WindowsPowerShell\v1.0\powershell.exe" -NoProfile -NonInteractive -ExecutionPolicy Bypass -File 'C:\ProgramData\REF\REF-Service-Baseline.ps1' -Mode Fix -Quick | Out-Null } catch { }
try { Get-ScheduledTask -TaskName 'PushLaunch' -ErrorAction SilentlyContinue | Where-Object TaskPath -like '\Microsoft\Windows\EnterpriseMgmt\*' | Start-ScheduledTask -ErrorAction SilentlyContinue } catch { }
'@
$guard = @'

# ---- v2 policy guard: locked runner, event-triggered task, audit SACL on policy keys ----
$runnerPath = 'C:\ProgramData\REF\REF-STIG-Guard.ps1'; $taskName = 'REF-Policy-Guard'
$taskArgs = '-NoProfile -NonInteractive -ExecutionPolicy Bypass -File "C:\ProgramData\REF\REF-STIG-Guard.ps1"'
$subscription = '<QueryList><Query Id="0" Path="Security"><Select Path="Security">*[System[(EventID=4657)]] and *[EventData[Data[@Name=''SubjectUserSid'']!=''S-1-5-18'']]</Select></Query></QueryList>'
$auditKeys = 'HKLM:\SOFTWARE\Policies', 'HKLM:\SOFTWARE\Microsoft\PolicyManager\current'
function Norm($s) { ($s -replace "`r`n", "`n").Trim() }
function Stamp($s) { if ("$s" -match 'REF-BUILD:\s*(\d{12})') { [long]$Matches[1] } else { [long]0 } }
function Test-RunnerAcl($p) { @((Get-Acl -LiteralPath $p).Access | Where-Object { $_.AccessControlType -eq 'Allow' -and "$($_.FileSystemRights)" -match 'Write|Modify|FullControl|ChangePermissions|TakeOwnership|Delete' -and "$($_.IdentityReference)" -notmatch '^(NT AUTHORITY\\SYSTEM|BUILTIN\\Administrators)$' }).Count -eq 0 }
function Test-GuardTask {
    $t = Get-ScheduledTask -TaskName $taskName -ErrorAction SilentlyContinue
    if (-not $t) { return 'missing' }; if ("$($t.State)" -eq 'Disabled') { return 'disabled' }
    if ("$($t.Principal.UserId)" -notmatch 'SYSTEM') { return "runs as $($t.Principal.UserId)" }
    if ("$($t.Actions[0].Arguments)" -ne $taskArgs) { return 'action changed' }
    if (-not @($t.Triggers | Where-Object { $_.CimClass.CimClassName -eq 'MSFT_TaskBootTrigger' }).Count) { return 'no startup trigger' }
    $ev = @($t.Triggers | Where-Object { $_.CimClass.CimClassName -eq 'MSFT_TaskEventTrigger' }); if (-not $ev.Count) { return 'no registry-change trigger' }
    if ("$($ev[0].Subscription)" -ne $subscription) { return 'registry-change trigger outdated' }
    'ok'
}
function Test-AuditSacl($k) { try { $a = Get-Acl -Path $k -Audit -ErrorAction Stop; [bool]@($a.Audit | Where-Object { "$($_.IdentityReference)" -match 'Everyone' -and "$($_.RegistryRights)" -match 'SetValue' -and "$($_.AuditFlags)" -match 'Success' }).Count } catch { $false } }
function Get-GuardNeeds($core) {
    $n = @()
    if (-not (Test-Path -LiteralPath $runnerPath)) { $n += 'guard runner missing' }
    elseif ((Norm (Get-Content -LiteralPath $runnerPath -Raw)) -ne (Norm $core) -and (Stamp (Get-Content -LiteralPath $runnerPath -Raw)) -le (Stamp $core)) { $n += 'guard runner differs from the tenant copy' }
    elseif (-not (Test-RunnerAcl $runnerPath)) { $n += 'guard runner writable by a non-administrator' }
    $ts = Test-GuardTask; if ($ts -ne 'ok') { $n += "guard task: $ts" }
    foreach ($k in $auditKeys) { if (-not (Test-AuditSacl $k)) { $n += "no audit SACL on $k" } }
    , $n
}
function Install-Guard($core) {
    $log = @()
    New-Item -ItemType Directory -Force -Path (Split-Path $runnerPath) | Out-Null
    if (-not (Test-Path -LiteralPath $runnerPath)) { Set-Content -LiteralPath $runnerPath -Value $core -Encoding UTF8; $log += 'guard runner written' }
    elseif ((Norm (Get-Content -LiteralPath $runnerPath -Raw)) -ne (Norm $core)) { if ((Stamp (Get-Content -LiteralPath $runnerPath -Raw)) -gt (Stamp $core)) { $log += 'installed guard runner is newer - kept' } else { Set-Content -LiteralPath $runnerPath -Value $core -Encoding UTF8; $log += 'guard runner written' } }
    if (-not (Test-RunnerAcl $runnerPath)) { & "$env:SystemRoot\System32\icacls.exe" $runnerPath /inheritance:r /grant:r '*S-1-5-18:(F)' '*S-1-5-32-544:(F)' '*S-1-5-32-545:(RX)' | Out-Null; $log += "guard runner locked (icacls exit $LASTEXITCODE)" }
    foreach ($k in $auditKeys) {
        if (Test-AuditSacl $k) { continue }
        try { $a = Get-Acl -Path $k -Audit -ErrorAction Stop
              $rule = New-Object System.Security.AccessControl.RegistryAuditRule('Everyone', 'SetValue, CreateSubKey, Delete, ChangePermissions, TakeOwnership', 'ContainerInherit', 'None', 'Success')
              $a.AddAuditRule($rule); Set-Acl -Path $k -AclObject $a -ErrorAction Stop; $log += "audit SACL set on $k" }
        catch { $log += "NOTE audit SACL on $k could not be set: $($_.Exception.Message)" }
    }
    if ((Test-GuardTask) -ne 'ok') {
        $a  = New-ScheduledTaskAction -Execute "$env:SystemRoot\System32\WindowsPowerShell\v1.0\powershell.exe" -Argument $taskArgs
        $t1 = New-ScheduledTaskTrigger -AtStartup
        $cls = Get-CimClass -Namespace 'Root/Microsoft/Windows/TaskScheduler' -ClassName MSFT_TaskEventTrigger
        $t2 = New-CimInstance -CimClass $cls -ClientOnly; $t2.Enabled = $true; $t2.Subscription = $subscription
        $p  = New-ScheduledTaskPrincipal -UserId 'SYSTEM' -LogonType ServiceAccount -RunLevel Highest
        $s  = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable -MultipleInstances IgnoreNew -ExecutionTimeLimit (New-TimeSpan -Minutes 5)
        Register-ScheduledTask -TaskName $taskName -Description 'Sanctir: re-applies tenant STIG settings the moment a policy registry value is changed by a non-SYSTEM account, re-checks services and kicks an MDM sync. Read C:\ProgramData\REF\REF-STIG-Guard.ps1 for exactly what it does.' -Action $a -Trigger $t1, $t2 -Principal $p -Settings $s -Force | Out-Null
        $log += 'guard task registered' }
    , $log
}
'@
$coreLit = "`$guardCore = @'`n" + $runnerBody + "`n'@`n"
$detect = $common + $guard + $coreLit + @'

# ---- DETECTION (read-only) ----
try { Invoke-StigGap } catch { Write-Output "ERROR: $($_.Exception.Message)"; exit 1 }
$gn = Get-GuardNeeds $guardCore
if ($script:Gaps.Count -or $gn.Count) { Write-Output ("NOT COMPLIANT ($($script:Gaps.Count + $gn.Count)): " + (@($script:Gaps) + @($gn) -join ' | ')); exit 1 }
Write-Output 'COMPLIANT: all STIG gap-closure settings in place; policy guard present, locked, armed'; exit 0
'@
$remediate = $common + $guard + $coreLit + @'

# ---- REMEDIATION ----
$glog = Install-Guard $guardCore
try { Invoke-StigGap -Write } catch { Write-Output "ERROR while fixing: $($_.Exception.Message)"; exit 1 }
$fixed = @($script:Gaps); $script:Gaps.Clear()
try { Invoke-StigGap } catch { Write-Output "ERROR while re-checking: $($_.Exception.Message)"; exit 1 }
$gn = Get-GuardNeeds $guardCore
if ($script:Gaps.Count -or @($gn | Where-Object { $_ -notmatch '^NOTE' }).Count) { Write-Output ("FIXED $($fixed.Count); STILL OPEN ($($script:Gaps.Count + $gn.Count)): " + (@($script:Gaps) + @($gn) -join ' | ') + " | guard: " + ($glog -join '; ')); exit 1 }
Write-Output ("FIXED $($fixed.Count): " + ($fixed -join ' | ') + " | guard: " + ($glog -join '; ')); exit 0
'@
foreach ($pair in @(@('REF-STIGGap-Detect.ps1', $detect), @('REF-STIGGap-Remediate.ps1', $remediate), @('REF-STIGGap-GuardRunner.ps1', $runnerBody))) {
    $p = Join-Path $here $pair[0]; [IO.File]::WriteAllText($p, $pair[1], (New-Object Text.UTF8Encoding($true)))
    $e = $null; [void][System.Management.Automation.Language.Parser]::ParseFile($p, [ref]$null, [ref]$e)
    '{0}  {1:n0} bytes  {2}  sha256-8 {3}' -f $pair[0], (Get-Item $p).Length, $(if ($e) { "PARSE ERROR: $($e[0].Message) line $($e[0].Extent.StartLineNumber)" } else { 'parse OK' }), (Get-FileHash $p -Algorithm SHA256).Hash.Substring(0, 8)
}
