# REF-OneDriveHealth-Build.ps1 - builds v1 of the OneDrive Health remediation (21 Oct 2026). Writes
# REF-OneDriveHealth-Detect.ps1 and -Remediate.ps1 next to this file from ONE core, so detection and remediation can never disagree.
#
# WHY. 21 Oct 2026: a script written on WS01 at 07:46 (uploaded, in sync) never reached WS02 - user's OneDrive there sat in
# a disconnected session and showed "hasn't synced in 14 hours" until the Security Officer went back into the session. Nothing told
# anyone. Security Officer: "Make it so once a computer creates a file immediately everywhere else it's uploaded and synced";
# "Never should these sessions go stale". OneDrive itself is already tenant-configured for zero sign-ins (SilentAccountConfig=1,
# Files On-Demand, KFM, Run key /background - read on WS01 21 Oct); what was missing is anything that notices a stalled client.
# WHAT. SYSTEM, hourly, every PC. For each signed-in user (console or disconnected) who has a work OneDrive (Accounts\Business1):
#   - heartbeat: the core re-creates <OneDrive>\.REF-SyncHealth\<COMPUTER>.txt every run. A healthy client uploads it within
#     seconds and turns it into a cloud placeholder (ReparsePoint attribute). Still a plain file 45+ minutes later = sync stalled.
#   - OneDrive not running for that user = not running.
#   Detect exits 1 on either; Remediate stops the stuck OneDrive and starts it again IN THAT USER'S SESSION (one-shot scheduled task,
#   user's own token, removed straight after) - no admin rights or sign-in for the user. Events in the REF log:
#   4301 stalled -> restarted, 4302 not running -> started, 4303 still stalled after a restart in the last 3 h (needs a person).
# GUARDS. Skips the whole run for 30 minutes after a boot or wake (OneDrive is catching up, not stalled); restarts a user's OneDrive
# at most once per 3 hours; skips users without a work OneDrive (admin is unlicensed); skips if Files On-Demand is not on
# (the placeholder test needs it). Never touches the sign-in, the firewall, or any OneDrive setting.
# WAY BACK: disable the remediation in Intune; delete the .REF-SyncHealth folder from OneDrive.
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path

$core = @'
# REF OneDrive Health core v1 (21 Oct 2026). Generated by REF-OneDriveHealth-Build.ps1 - do not edit by hand. SYSTEM, hourly.
$ErrorActionPreference = 'Continue'
$StaleMinutes = 45; $SettleMinutes = 30; $RestartGapHours = 3
$src = 'REF-OneDriveHealth'; $statePath = 'C:\ProgramData\REF\REF-OneDriveHealth.state.json'
$exeDefault = 'C:\Program Files\Microsoft OneDrive\OneDrive.exe'
function Log($id, $type, $msg) { try { if (-not [Diagnostics.EventLog]::SourceExists($src)) { New-EventLog -LogName REF -Source $src }; Write-EventLog -LogName REF -Source $src -EventId $id -EntryType $type -Message $msg } catch { } }
$now = Get-Date
# --- settle guard: boot or wake in the last 30 minutes
$boot = (Get-CimInstance Win32_OperatingSystem).LastBootUpTime
$wake = try { (Get-WinEvent -FilterHashtable @{ LogName = 'System'; ProviderName = 'Microsoft-Windows-Power-Troubleshooter'; Id = 1 } -MaxEvents 1 -ErrorAction Stop).TimeCreated } catch { $null }
$last = @($boot, $wake) | Where-Object { $_ } | Sort-Object -Descending | Select-Object -First 1
if (($now - $last).TotalMinutes -lt $SettleMinutes) { Write-Output "OneDrive Health: skipped - booted/woke $([int]($now - $last).TotalMinutes) min ago"; exit 0 }
if ((Get-ItemProperty 'HKLM:\SOFTWARE\Policies\Microsoft\OneDrive' -ErrorAction SilentlyContinue).FilesOnDemandEnabled -ne 1) { Write-Output 'OneDrive Health: skipped - Files On-Demand policy not on'; exit 0 }
$state = @{}; try { if (Test-Path $statePath) { (Get-Content $statePath -Raw | ConvertFrom-Json).PSObject.Properties | ForEach-Object { $state[$_.Name] = [datetime]$_.Value } } } catch { }
# --- signed-in users = owners of explorer.exe and OneDrive.exe
$procs = @(Get-CimInstance Win32_Process -Filter "Name='explorer.exe' OR Name='OneDrive.exe'")
$owner = @{}; foreach ($p in $procs) { try { $s = (Invoke-CimMethod -InputObject $p -MethodName GetOwnerSid).Sid; if ($s) { $owner[$p.ProcessId] = $s } } catch { } }
$sids = @($owner.Values | Where-Object { $_ -match '^S-1-(12-1|5-21)-' } | Select-Object -Unique)
$res = @()
foreach ($sid in $sids) {
    $acct = Get-ItemProperty "Registry::HKEY_USERS\$sid\Software\Microsoft\OneDrive\Accounts\Business1" -ErrorAction SilentlyContinue
    if (-not $acct -or -not $acct.UserFolder -or -not (Test-Path -LiteralPath $acct.UserFolder)) { continue }
    $name = try { (New-Object Security.Principal.SecurityIdentifier $sid).Translate([Security.Principal.NTAccount]).Value } catch { $sid }
    $od = @($procs | Where-Object { $_.Name -eq 'OneDrive.exe' -and $owner[$_.ProcessId] -eq $sid })
    $dir = Join-Path $acct.UserFolder '.REF-SyncHealth'; $hb = Join-Path $dir "$env:COMPUTERNAME.txt"
    $st = 'OK'; $why = ''
    if (-not $od) { $st = 'NOTRUNNING'; $why = 'OneDrive not running' }
    elseif (Test-Path -LiteralPath $hb) {
        $i = Get-Item -LiteralPath $hb -Force; $age = ($now - $i.LastWriteTime).TotalMinutes
        if (-not ($i.Attributes -band [IO.FileAttributes]::ReparsePoint) -and $age -ge $StaleMinutes) { $st = 'STALLED'; $why = "heartbeat not uploaded after $([int]$age) min" } }
    $res += [pscustomobject]@{ Sid = $sid; Name = $name; State = $st; Why = $why; Hb = $hb; Dir = $dir; Exe = $(if ($od -and $od[0].ExecutablePath) { $od[0].ExecutablePath } else { $exeDefault }); Procs = $od } }
function Beat($r) { try { New-Item -ItemType Directory -Force -Path $r.Dir | Out-Null; (Get-Item -LiteralPath $r.Dir -Force).Attributes = 'Directory, Hidden'
    if (Test-Path -LiteralPath $r.Hb) { Remove-Item -LiteralPath $r.Hb -Force }
    Set-Content -LiteralPath $r.Hb -Value "REF OneDrive Health heartbeat | $env:COMPUTERNAME | $($now.ToString('yyyy-MM-dd HH:mm:ss zzz'))" -Encoding UTF8 } catch { } }
$bad = @($res | Where-Object State -ne 'OK')
if ($Mode -eq 'Detect') {
    foreach ($r in @($res | Where-Object State -eq 'OK')) { Beat $r }
    $sum = if ($res) { ($res | ForEach-Object { "$($_.Name)=$($_.State)$(if ($_.Why) { " ($($_.Why))" })" }) -join '; ' } else { 'no signed-in user with a work OneDrive' }
    Write-Output "OneDrive Health: $sum"; if ($bad) { exit 1 }; exit 0 }
# --- Remediate
$out = @(); $fail = $false
foreach ($r in $bad) {
    if ($state[$r.Sid] -and ($now - $state[$r.Sid]).TotalHours -lt $RestartGapHours) {
        Log 4303 Warning "OneDrive for $($r.Name) still $($r.State) ($($r.Why)) after a restart at $($state[$r.Sid]) - needs a person (open OneDrive in that user's session)."
        $out += "$($r.Name): still $($r.State) after restart at $($state[$r.Sid].ToString('HH:mm')) - left alone"; $fail = $true; continue }
    foreach ($p in $r.Procs) { try { Stop-Process -Id $p.ProcessId -Force -ErrorAction Stop } catch { } }
    Start-Sleep -Seconds 3
    $tn = "REF-OneDriveHealth-Start-$([guid]::NewGuid().ToString('N').Substring(0,8))"
    try {
        $pr = New-ScheduledTaskPrincipal -UserId $r.Name -LogonType Interactive -RunLevel Limited
        Register-ScheduledTask -TaskName $tn -Action (New-ScheduledTaskAction -Execute $r.Exe -Argument '/background') -Principal $pr -Settings (New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -ExecutionTimeLimit (New-TimeSpan -Minutes 5)) -Force | Out-Null
        Start-ScheduledTask -TaskName $tn; Start-Sleep -Seconds 20
    } catch { $out += "$($r.Name): start failed - $($_.Exception.Message)"; $fail = $true }
    finally { Unregister-ScheduledTask -TaskName $tn -Confirm:$false -ErrorAction SilentlyContinue }
    $up = @(Get-CimInstance Win32_Process -Filter "Name='OneDrive.exe'" | Where-Object { try { (Invoke-CimMethod -InputObject $_ -MethodName GetOwnerSid).Sid -eq $r.Sid } catch { $false } })
    if ($up) {
        $state[$r.Sid] = $now; Beat $r
        $id = if ($r.State -eq 'STALLED') { 4301 } else { 4302 }
        Log $id Information "OneDrive for $($r.Name) was $($r.State) ($($r.Why)); restarted in the user's session (pid $($up[0].ProcessId))."
        $out += "$($r.Name): $($r.State) -> restarted (pid $($up[0].ProcessId))" }
    else { Log 4303 Warning "OneDrive for $($r.Name) was $($r.State) ($($r.Why)); restart did not bring it up."; $out += "$($r.Name): restart did not bring OneDrive up"; $fail = $true } }
try { New-Item -ItemType Directory -Force -Path (Split-Path $statePath) | Out-Null; $o = @{}; foreach ($k in $state.Keys) { $o[$k] = $state[$k].ToString('o') }; $o | ConvertTo-Json | Set-Content $statePath -Encoding UTF8 } catch { }
Write-Output ("OneDrive Health remediation: " + $(if ($out) { $out -join '; ' } else { 'nothing to do' }))
if ($fail) { exit 1 }; exit 0
'@

$hdr = "# Built $(Get-Date -Format 'yyyy-MM-dd HH:mm') by REF-OneDriveHealth-Build.ps1`r`n"
[IO.File]::WriteAllText((Join-Path $here 'REF-OneDriveHealth-Detect.ps1'), $hdr + "`$Mode = 'Detect'`r`n" + $core, (New-Object Text.UTF8Encoding $true))
[IO.File]::WriteAllText((Join-Path $here 'REF-OneDriveHealth-Remediate.ps1'), $hdr + "`$Mode = 'Remediate'`r`n" + $core, (New-Object Text.UTF8Encoding $true))
Get-ChildItem $here -Filter 'REF-OneDriveHealth-*.ps1' | ForEach-Object { "{0}  {1} bytes  SHA256 {2}" -f $_.Name, $_.Length, (Get-FileHash $_.FullName).Hash.Substring(0, 8) }
