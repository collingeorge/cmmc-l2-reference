function Get-Ver($path) { $m = [regex]::Match($path, '\d+(\.\d+){2,3}'); if ($m.Success) { try { return [version]$m.Value } catch { } }; return [version]'0.0' }
function Get-Newest($globs) {
    $files = @(foreach ($g in $globs) { Get-ChildItem -Path $g -File -ErrorAction SilentlyContinue | Where-Object { $_.FullName -notlike 'C:\Users\WS01_admin\*' } })
    @($files | Sort-Object @{ Expression = { Get-Ver $_.FullName }; Descending = $true }, @{ Expression = { $_.LastWriteTime }; Descending = $true })
}
$out = @(); $changed = 0
foreach ($t in $targets) {
    $proto = if ($t.Protocol) { $t.Protocol } else { 'TCP' }
    $found = @(Get-Newest $t.Glob)
    if ($found.Count -eq 0) { continue }   # not installed here: nothing to enforce
    $wanted = if ($t.PerUser) { @($found | Group-Object { $_.FullName.Split('\')[2] } | ForEach-Object { $_.Group | Select-Object -First 1 }) } else { @($found | Select-Object -First 1) }
    foreach ($w in $wanted) {
        $rn = if ($t.PerUser) { "$($t.Name) ($($w.FullName.Split('\')[2]))" } else { $t.Name }
        $rules = @(Get-NetFirewallRule -PolicyStore PersistentStore -DisplayName $rn -ErrorAction SilentlyContinue)
        if ($rules.Count -eq 0) {
            if ($Mode -eq 'Fix') { New-NetFirewallRule -DisplayName $rn -Group 'REF-Remediated' -Direction Outbound -Action Allow -Enabled True -Profile Any -Protocol $proto -RemotePort $t.Ports -Program $w.FullName -Description 'Maintained by REF-FW-VersionedPaths (Intune remediation and 5-minute runner)' | Out-Null; $out += "$rn : created -> $($w.FullName)"; $changed++ }
            else { $out += "NEED $rn : missing (binary $($w.FullName))" }
            continue
        }
        if ($rules.Count -gt 1) {
            if ($Mode -eq 'Fix') { $rules | Select-Object -Skip 1 | ForEach-Object { Remove-NetFirewallRule -Name $_.Name }; $out += "$rn : $($rules.Count - 1) duplicate copy removed"; $changed++ }
            else { $out += "NEED $rn : $($rules.Count) copies" }
        }
        $r = $rules[0]; $prog = ($r | Get-NetFirewallApplicationFilter).Program; $pf = $r | Get-NetFirewallPortFilter
        $why = @()
        if ($prog -ne $w.FullName) { $why += "program $prog" }
        if ("$($pf.Protocol)" -ne $proto) { $why += "protocol $($pf.Protocol)" }
        if ((@($pf.RemotePort) -join ',') -ne ($t.Ports -join ',')) { $why += "ports $(@($pf.RemotePort) -join ',')" }
        if ("$($r.Enabled)" -ne 'True' -or "$($r.Action)" -ne 'Allow' -or "$($r.Direction)" -ne 'Outbound') { $why += "state $($r.Enabled)/$($r.Action)/$($r.Direction)" }
        if (-not $why.Count) { continue }
        if ($Mode -eq 'Fix') { Set-NetFirewallRule -Name $r.Name -Program $w.FullName -Protocol $proto -RemotePort $t.Ports -Enabled True -Action Allow -Direction Outbound -Profile Any; $out += "$rn : corrected ($($why -join '; ')) -> $($w.FullName)"; $changed++ }
        else { $out += "NEED $rn : $($why -join '; '); newest $($w.FullName)" }
    }
}
